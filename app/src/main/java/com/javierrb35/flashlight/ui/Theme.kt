/** User-selectable appearance. DARK is the default: a torch lives in the dark. */
enum class ThemeMode { SYSTEM, LIGHT, DARK }

/**
 * App theme. Torch-amber identity by default in dark; light and system
 * options available; optional Material You dynamic color on Android 12+.
 */
@Composable
fun FlashLightTheme(
    themeMode: ThemeMode = ThemeMode.DARK,
    dynamicColor: Boolean = false,
    content: @Composable () -> Unit,
) {
    val dark = when (themeMode) {
        ThemeMode.SYSTEM -> isSystemInDarkTheme()
        ThemeMode.LIGHT -> false
        ThemeMode.DARK -> true
    }
    val colorScheme = when {
        dynamicColor && Build.VERSION.SDK_INT >= Build.VERSION_CODES.S -> {
            val context = LocalContext.current
            if (dark) dynamicDarkColorScheme(context) else dynamicLightColorScheme(context)
        }

        dark -> DarkColors
        else -> LightColors
    }
    MaterialTheme(
        colorScheme = colorScheme,
        typography = FlashLightTypography,
        content = content,
    )
}
